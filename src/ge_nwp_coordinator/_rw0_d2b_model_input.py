def require_current_d2_basis(
    checkpoint: RW0D2EvidenceCheckpointV1,
    current: RW0D2CurrentOwnerSnapshotV1,
) -> None:
    """Refuse a stale phase, changed head/selection/stop, or expired source."""
    if (type(checkpoint) is not RW0D2EvidenceCheckpointV1
            or type(current) is not RW0D2CurrentOwnerSnapshotV1):
        raise RW0D2BInputConflict() from None
    checkpoint.validate()
    current.validate()
    basis = checkpoint.d1_handback.phase_basis
    phase = _resolve_d2_checked_layout(checkpoint.d1_handback).family(
        checkpoint.admitted_families, "worker_observation:000",
    ).phase
    if (current.phase_basis_ref != basis.basis_ref
            or current.phase_basis_digest != basis.basis_digest
            or current.program_head_revision != phase.value("expected_program_head_revision")
            or current.program_head_digest != phase.value("expected_program_head_digest")
            or current.work_item_head_revision != phase.value("expected_work_item_head_revision")
            or current.work_item_head_digest != phase.value("expected_work_item_head_digest")
            or current.selection_head_revision != basis.selection_head_revision
            or current.selection_head_digest != basis.selection_head_digest
            or current.author_effect_head_revision != basis.current_effect_head_revision
            or current.author_effect_head_digest != basis.current_effect_head_digest
            or current.author_delivery_head_revision != basis.current_delivery_head_revision
            or current.author_delivery_head_digest != basis.current_delivery_head_digest
            or current.global_stop.stop_ref != basis.global_stop_ref
            or current.global_stop.version != basis.global_stop_version
            or current.global_stop.status.value != basis.global_stop_state
            or current.global_stop.active
            or any(current.observed_at >= valid_until for valid_until in (
                checkpoint.d1_handback.author_command.attempt_fence.expires_at,
                checkpoint.d1_handback.author_command.effect_fence.expires_at,
                *(proof.current_fence.expires_at for proof in checkpoint.bound_effects),
                *(source.observation_expires_at for source in checkpoint.authority_sources),
                checkpoint.readiness_source.expires_at,
                checkpoint.validation_result_set.expires_at,
                checkpoint.review_result_set.expires_at,
                checkpoint.validation_disposition.expires_at,
                checkpoint.review_disposition.expires_at,
                checkpoint.policy_sources[0].expires_at,
                checkpoint.policy_sources[1].expires_at,
                checkpoint.policy_sources[4].expires_at,
                checkpoint.policy_matrices[0].expires_at,
                checkpoint.policy_matrices[1].expires_at,
            ))):
        raise RW0D2BInputConflict() from None


