def _evaluate_parent_owned_branch_entries(value: object) -> _PostExecutionValue:
    if type(value) not in {PostExecutionStandingPolicyBranchMatrixV1, PostExecutionRiskLaneBranchMatrixV1}:
        _fail("evaluation_contract_mismatch")
    value._validate_value()
    mapping = value.to_mapping()
    entries = typing.cast(list[dict[str, object]], mapping["entries"])
    expected: list[tuple[str, str]] = []
    for branch, applicability, effect_class in _CANONICAL_MATRIX_BRANCHES:
        if type(value) is PostExecutionStandingPolicyBranchMatrixV1:
            if applicability == "halt_only":
                outcome = ("permit", "halt_only_policy_not_applicable")
            elif mapping["policy_revocation_status"] == "revoked":
                outcome = ("deny", "policy_revoked")
            elif mapping["evaluated_at"] < mapping["not_before"]:
                outcome = ("deny", "policy_not_yet_valid")
            elif mapping["evaluated_at"] >= mapping["expires_at"]:
                outcome = ("deny", "policy_expired")
            elif branch not in mapping["allowed_branches"]:
                outcome = ("deny", "branch_not_allowed")
            elif mapping["risk_lane"] not in mapping["allowed_risk_lanes"]:
                outcome = ("deny", "risk_lane_not_allowed")
            elif effect_class not in mapping["allowed_effect_classes"]:
                outcome = ("deny", "effect_class_not_allowed")
            elif mapping["policy_status"] == "unknown":
                outcome = ("unknown", "policy_status_unknown")
            elif mapping["policy_status"] != "active":
                outcome = ("unknown", "policy_currentness_unknown")
            else:
                outcome = ("permit", "policy_permits")
        else:
            if applicability == "halt_only":
                outcome = ("permit", "halt_only_risk_not_applicable")
            elif mapping["policy_revocation_status"] == "revoked":
                outcome = ("deny", "policy_revoked")
            elif mapping["evaluated_at"] < mapping["not_before"]:
                outcome = ("deny", "policy_not_yet_valid")
            elif mapping["evaluated_at"] >= mapping["expires_at"]:
                outcome = ("deny", "policy_expired")
            elif mapping["risk_lane"] != mapping["required_risk_lane"]:
                outcome = ("deny", "required_lane_mismatch")
            elif mapping["risk_lane"] not in mapping["allowed_risk_lanes"]:
                outcome = ("deny", "risk_lane_not_allowed")
            elif mapping["policy_status"] == "unknown":
                outcome = ("unknown", "policy_status_unknown")
            else:
                outcome = ("permit", "risk_lane_permits")
        expected.append(outcome)
    if tuple((entry["result"], entry["reason"]) for entry in entries) != tuple(expected):
        _fail("evaluation_contract_mismatch")
    return typing.cast(_PostExecutionValue, value)


