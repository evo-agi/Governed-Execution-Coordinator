def _require_source_equal(
    candidate: _PostExecutionValue,
    source: _PostExecutionValue,
    pairs: tuple[tuple[str, str], ...],
) -> None:
    if any(
        not _exact_equal(getattr(candidate, target), getattr(source, origin))
        for target, origin in pairs
    ):
        _fail("source_owner_mismatch")


def validate_post_execution_risk_lane_matrix_relation(
    value: object,
    *,
    risk_policy: object,
    source_profile: object,
    source_binding: object,
) -> PostExecutionRiskLaneBranchMatrixV1:
    """Derive and verify a risk matrix from exact owner-supplied sources."""

    candidate = typing.cast(
        PostExecutionRiskLaneBranchMatrixV1,
        PostExecutionRiskLaneBranchMatrixV1.from_supplied(value),
    )
    policy = typing.cast(
        PostExecutionRiskPolicyAttestationV1,
        PostExecutionRiskPolicyAttestationV1.from_supplied(risk_policy),
    )
    profile = typing.cast(
        PostExecutionRiskSourceProfileV1,
        PostExecutionRiskSourceProfileV1.from_supplied(source_profile),
    )
    binding = typing.cast(
        PostExecutionRiskSourceBindingV1,
        PostExecutionRiskSourceBindingV1.from_supplied(source_binding),
    )
    _require_source_equal(candidate, policy, (
        ("risk_policy_schema_id", "schema_id"), ("risk_policy_ref", "attestation_ref"),
        ("risk_policy_digest", "attestation_digest"), ("matrix_author_ref", "source_owner_ref"),
        ("matrix_author_invocation_ref", "source_owner_invocation_ref"),
        ("policy_status", "policy_status"), ("policy_revocation_status", "revocation_status"),
        ("allowed_risk_lanes", "allowed_risk_lanes"), ("required_risk_lane", "required_risk_lane"),
        ("not_before", "not_before"), ("expires_at", "expires_at"),
        ("evaluated_at", "evaluated_at"),
    ))
    _require_source_equal(candidate, profile, (
        ("source_profile_schema_id", "schema_id"), ("source_profile_ref", "source_profile_ref"),
        ("source_profile_digest", "source_profile_digest"),
    ))
    _require_source_equal(candidate, binding, (
        ("source_binding_schema_id", "schema_id"), ("source_binding_ref", "source_binding_ref"),
        ("source_binding_digest", "source_binding_digest"), ("development_work_item_ref", "development_work_item_ref"),
        ("risk_lane", "risk_lane"),
    ))
    if (
        binding.source_profile_schema_id != profile.schema_id
        or binding.source_profile_ref != profile.source_profile_ref
        or binding.source_profile_digest != profile.source_profile_digest
        or policy.source_profile_schema_id != profile.schema_id
        or policy.source_profile_ref != profile.source_profile_ref
        or policy.source_profile_digest != profile.source_profile_digest
    ):
        _fail("source_owner_mismatch")
    return typing.cast(PostExecutionRiskLaneBranchMatrixV1, _evaluate_parent_owned_branch_entries(candidate))


